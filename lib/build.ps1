# Build: evaluate the configuration into a static, content-addressed
# artifact. Switch applies an artifact and never evaluates again.
Set-StrictMode -Version Latest

# Home files keep their target names. Build gives each one its chezmoi
# source name, so a name never acts as a chezmoi attribute.
$script:NwChezmoiPrefixes = @('after_', 'before_', 'create_', 'dot_', 'empty_', 'encrypted_', 'exact_', 'executable_', 'external_', 'literal_', 'modify_', 'once_', 'onchange_', 'private_', 'readonly_', 'remove_', 'run_', 'symlink_')
$script:NwChezmoiSuffixes = @('.tmpl', '.literal', '.age', '.asc')

function ConvertTo-NwSourceName {
    param([string]$Name, [switch]$File, [switch]$Empty)
    $prefix = ''
    if ($File -and $Empty) { $prefix = 'empty_' }

    if ($Name.StartsWith('.')) {
        $prefix += 'dot_'
        $Name = $Name.Substring(1)
    } elseif (@($script:NwChezmoiPrefixes | Where-Object { $Name.StartsWith($_) }).Count -gt 0) {
        $prefix += 'literal_'
    }

    $suffix = ''
    if ($File -and @($script:NwChezmoiSuffixes | Where-Object { $Name.EndsWith($_) }).Count -gt 0) { $suffix = '.literal' }
    return $prefix + $Name + $suffix
}

function ConvertTo-NwSourcePath {
    param([string]$Target, [switch]$Empty)
    $parts = @($Target -split '/')

    $source = for ($i = 0; $i -lt $parts.Count; $i++) {
        $last = $i -eq $parts.Count - 1
        ConvertTo-NwSourceName -Name $parts[$i] -File:$last -Empty:($last -and $Empty)
    }

    return ($source -join '/')
}

function Get-NwRelativePath {
    param([string]$Root, [string]$Path)
    $rootFull = [System.IO.Path]::GetFullPath($Root).TrimEnd('\') + '\'
    $full = [System.IO.Path]::GetFullPath($Path)

    if (-not $full.StartsWith($rootFull, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "'$Path' is outside '$Root'."
    }

    return $full.Substring($rootFull.Length).Replace('\', '/')
}

function Get-NwHomeFiles {
    param([string]$Root, [string]$Owner)
    $files = @()
    if (-not (Test-Path -LiteralPath $Root -PathType Container)) { return , $files }

    foreach ($item in Get-ChildItem -LiteralPath $Root -Recurse -Force) {
        if ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) {
            throw "'$($item.FullName)' is a link. Declare static files only."
        }

        if ($item.PSIsContainer) { continue }
        $relative = Get-NwRelativePath -Root $Root -Path $item.FullName
        if ($relative -match '(^|/)\.chezmoi') { throw "'$relative': chezmoi special files are generated by nacre-windows." }

        $files += @{
            Owner  = $Owner
            Source = $item.FullName
            Path   = ConvertTo-NwSourcePath -Target $relative -Empty:($item.Length -eq 0)
            Target = $relative
            Sha256 = Get-NwFileSha256 $item.FullName
        }
    }

    return , $files
}

function Test-NwPathWithin {
    param([string]$Path, [string]$Directory)

    return ([string]::Equals($Path, $Directory, [StringComparison]::OrdinalIgnoreCase) -or
        $Path.StartsWith($Directory + '/', [StringComparison]::OrdinalIgnoreCase))
}

function Resolve-NwHomeFiles {
    param([System.Collections.IDictionary]$Config, [string]$CoreRoot, [string]$MachineRoot, [string[]]$SourceTargets)

    if (Test-Path -LiteralPath (Join-Path $MachineRoot 'home')) {
        throw "'$(Join-Path $MachineRoot 'home')' is the old home file directory. Move its files to 'files' under their target names, such as files/.config/x."
    }

    $core = Get-NwHomeFiles -Root (Join-Path (Join-Path $CoreRoot 'files') 'home') -Owner 'core'
    $machine = Get-NwHomeFiles -Root (Join-Path $MachineRoot 'files') -Owner 'machine'

    $coreTargets = @{}
    foreach ($file in $core) { $coreTargets[$file.Target.ToLowerInvariant()] = $file }

    foreach ($target in $Config['Files'].Keys) {
        if (-not $coreTargets.ContainsKey(([string]$target).ToLowerInvariant())) {
            throw "Files.'$target' names no core file. Core files: $((@($core | ForEach-Object { $_.Target }) | Sort-Object) -join ', ')."
        }
    }

    $selected = @{}

    foreach ($file in $core) {
        $enabled = $true

        foreach ($target in $Config['Files'].Keys) {
            if ([string]$target -ieq $file.Target) { $enabled = $Config['Files'][$target] }
        }

        if ($enabled) { $selected[$file.Target.ToLowerInvariant()] = $file }
    }

    foreach ($file in $machine) {
        $key = $file.Target.ToLowerInvariant()

        if ($selected.ContainsKey($key)) {
            throw "'$($file.Target)' has two owners: the core and the machine. Set Files = @{ '$($file.Target)' = `$false } to take it over."
        }

        $selected[$key] = $file
    }

    foreach ($file in $selected.Values) {
        foreach ($directory in $SourceTargets) {
            if (Test-NwPathWithin $file.Target $directory) {
                throw "'$($file.Target)' is inside '$directory', which a source owns."
            }
        }
    }

    $keys = @(Get-NwSortedKeys $selected)
    return , @($keys | ForEach-Object { $selected[$_] })
}

function ConvertTo-NwYamlString {
    param([string]$Text)
    return "'" + $Text.Replace("'", "''") + "'"
}

function New-NwWinGetDocument {
    param([System.Collections.IDictionary]$Config, [switch]$UseLatest)

    $lines = @(
        '# Generated by nacre-windows. Edit machine.psd1 instead.'
        '$schema: https://raw.githubusercontent.com/PowerShell/DSC/main/schemas/2023/08/config/document.json'
        'metadata:'
        '  winget:'
        '    processor:'
        '      identifier: dscv3'
        'resources:'
    )

    $packages = $Config['Packages']
    $count = 0

    foreach ($id in (Get-NwSortedKeys $packages)) {
        $package = $packages[$id]
        if (-not $package['Enable']) { continue }
        $count++
        $source = 'winget'
        if ($package.ContainsKey('Source')) { $source = $package['Source'] }
        $lines += '  - type: Microsoft.WinGet/Package'
        $lines += '    name: ' + (ConvertTo-NwYamlString ($id -replace '[^A-Za-z0-9]', '-'))
        $lines += '    properties:'
        $lines += '      id: ' + (ConvertTo-NwYamlString $id)
        $lines += '      source: ' + (ConvertTo-NwYamlString $source)

        if ($package.ContainsKey('Version') -and $package['Version']) {
            $lines += '      version: ' + (ConvertTo-NwYamlString $package['Version'])
        } elseif ($UseLatest -and -not ($package.ContainsKey('Hold') -and $package['Hold'])) {
            $lines += '      useLatest: true'
        }
    }

    if ($count -eq 0) { $lines[-1] = 'resources: []' }
    return (($lines -join "`n") + "`n")
}

function Get-NwSourceTargets {
    param([System.Collections.IDictionary]$Config)
    $targets = @{}

    foreach ($name in (Get-NwSortedKeys $Config['Sources'])) {
        $source = $Config['Sources'][$name]

        if ($source['Enable']) {
            $targets[$name] = (($Config['ConfigHome'] -replace '\\', '/').Trim('/')) + '/' + $source['Target']
        }
    }

    return $targets
}

# Sources with a Development path are links to a local worktree, not
# archives: Name -> @{ Target; Path }.
function Get-NwSourceLinks {
    param([System.Collections.IDictionary]$Config, [System.Collections.IDictionary]$Targets)
    $links = @{}

    foreach ($name in (Get-NwSortedKeys $Targets)) {
        foreach ($key in $Config['Development'].Keys) {
            if ([string]$key -ieq $name) {
                $links[$name] = @{ Target = $Targets[$name]; Path = [string]$Config['Development'][$key] }
            }
        }
    }

    return $links
}

function New-NwExternalDocument {
    param([System.Collections.IDictionary]$Targets, [System.Collections.IDictionary]$Pins)
    $lines = @('# Generated by nacre-windows. Pin sources with nacre-windows lock.')

    foreach ($name in (Get-NwSortedKeys $Targets)) {
        $pin = $Pins[$name]
        $lines += ''
        $lines += '[' + (ConvertTo-NwJsonString $Targets[$name]) + ']'
        $lines += '    type = "archive"'
        $lines += '    url = ' + (ConvertTo-NwJsonString (Get-NwArchiveUrl -Repo $pin['Repo'] -Rev $pin['Rev']))
        $lines += '    stripComponents = 1'
        # The archive owns the whole directory; chezmoi removes extra files.
        $lines += '    exact = true'
        $lines += '    checksum.sha256 = ' + (ConvertTo-NwJsonString $pin['Sha256'])
    }

    return (($lines -join "`n") + "`n")
}

# Each pinned dependency of an enabled module must be an enabled module
# inside every range, with each edition of the module that needs it.
function Assert-NwModulePins {
    param([System.Collections.IDictionary]$Config, [System.Collections.IDictionary]$Pins)
    $errors = @()

    foreach ($id in (Get-NwSortedKeys $Pins)) {
        $pin = $Pins[$id]
        $key = Find-NwKey $Config['Modules'] $id

        if ($pin['RequireLicenseAcceptance'] -and -not ($Config['Modules'][$key].ContainsKey('AcceptLicense') -and $Config['Modules'][$key]['AcceptLicense'])) {
            $errors += "Module '$id' requires license acceptance. Read its license, then set Modules.$key.AcceptLicense = `$true."
        }

        foreach ($name in (Get-NwSortedKeys $pin['Dependencies'])) {
            $declared = Find-NwKey $Config['Modules'] $name

            if (-not $declared) {
                $errors += "Module '$id' depends on '$name', which is not a declared module. Declare Modules = @{ '$name' = `$true }."
                continue
            }

            if (-not $Config['Modules'][$declared]['Enable']) {
                $errors += "Module '$id' depends on '$name', which is disabled."
                continue
            }

            $dependency = Find-NwKey $Pins $name
            $version = $Pins[$dependency]['Version']
            $ranges = @($pin['Dependencies'][$name])
            $outside = @($ranges | Where-Object { -not (Test-NwVersionInRange (ConvertTo-NwVersion $version) (ConvertTo-NwVersionRange $_)) })

            if ($outside.Count -gt 0) {
                $errors += "Module '$id' needs '$dependency' in $($ranges -join ' and '), but '$dependency' is pinned at $version."
            }

            $missing = @($pin['Editions'] | Where-Object { @($Pins[$dependency]['Editions']) -notcontains $_ })

            if ($missing.Count -gt 0) {
                $errors += "Module '$id' needs '$dependency' for $($missing -join ', '), but '$dependency' supports only $(@($Pins[$dependency]['Editions']) -join ', ')."
            }
        }
    }

    if ($errors.Count -gt 0) { throw ("Invalid modules:`n  " + ($errors -join "`n  ")) }
}

function Invoke-NwBuild {
    param([string]$CoreRoot, [string]$MachineRoot)
    $config = Resolve-NwConfiguration -CoreRoot $CoreRoot -MachineRoot $MachineRoot
    $targets = Get-NwSourceTargets $config
    $links = Get-NwSourceLinks -Config $config -Targets $targets
    $archives = @{}
    foreach ($name in $targets.Keys) { if (-not $links.ContainsKey($name)) { $archives[$name] = $targets[$name] } }
    $pins = Resolve-NwSourcePins -Config $config -CoreRoot $CoreRoot -MachineRoot $MachineRoot -Names @($archives.Keys)
    $modules = Resolve-NwModulePins -Config $config -CoreRoot $CoreRoot -MachineRoot $MachineRoot
    Assert-NwModulePins -Config $config -Pins $modules
    $files = Resolve-NwHomeFiles -Config $config -CoreRoot $CoreRoot -MachineRoot $MachineRoot -SourceTargets @($targets.Values)

    $documents = @{
        'configuration.winget'        = New-NwWinGetDocument $config
        'configuration-update.winget' = New-NwWinGetDocument $config -UseLatest
        'chezmoi.toml'                = "# Generated by nacre-windows. Keeps user chezmoi settings out of the apply.`n"
    }

    if ($archives.Count -gt 0) {
        $documents['home/.chezmoiexternal.toml'] = New-NwExternalDocument -Targets $archives -Pins $pins
    }

    $receipt = @{
        SchemaVersion = $script:NwSchemaVersion
        CoreVersion   = ([System.IO.File]::ReadAllText((Join-Path $CoreRoot 'VERSION'))).Trim()
        Configuration = $config
        Sources       = $pins
        Modules       = $modules
        Links         = $links
        Files         = @($files | ForEach-Object { @{ Owner = $_.Owner; Path = $_.Path; Target = $_.Target; Sha256 = $_.Sha256 } })
        Documents     = @{}
    }

    foreach ($name in $documents.Keys) { $receipt['Documents'][$name] = Get-NwTextSha256 $documents[$name] }
    # The identifier hashes every output, so equal inputs give equal artifacts.
    $id = (Get-NwTextSha256 (ConvertTo-NwJson $receipt)).Substring(0, 32)
    $receipt['Id'] = $id

    $builds = Join-Path (Get-NwStateRoot) 'builds'
    $path = Join-Path $builds $id

    if (-not (Test-Path -LiteralPath (Join-Path $path 'receipt.json'))) {
        $temporary = Join-Path $builds ($id + '.tmp-' + [guid]::NewGuid().ToString('N'))

        try {
            New-NwDirectory (Join-Path $temporary 'home')

            foreach ($file in $files) {
                $destination = Join-Path (Join-Path $temporary 'home') ($file.Path.Replace('/', '\'))
                New-NwDirectory (Split-Path -Parent $destination)
                Copy-Item -LiteralPath $file.Source -Destination $destination
            }

            foreach ($name in $documents.Keys) {
                Write-NwText (Join-Path $temporary ($name.Replace('/', '\'))) $documents[$name]
            }

            Write-NwJson (Join-Path $temporary 'receipt.json') $receipt
            if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path -Recurse -Force }
            Move-Item -LiteralPath $temporary -Destination $path
        } finally {
            if (Test-Path -LiteralPath $temporary) { Remove-Item -LiteralPath $temporary -Recurse -Force }
        }
    }

    return @{ Id = $id; Path = $path; Receipt = $receipt; Config = $config; Targets = $targets; Archives = $archives; Links = $links; Modules = $modules }
}
